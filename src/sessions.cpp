#include "sessions.h"
#include <QDir>
#include <QFile>
#include <QFileInfo>
#include <QJsonDocument>
#include <QJsonObject>
#include <QRandomGenerator>
#include <QRegularExpression>
#include <QStandardPaths>
#include <algorithm>

namespace ai {

QString sessionsDir()
{
    return QDir(QStandardPaths::writableLocation(QStandardPaths::GenericDataLocation)).filePath(QStringLiteral("geany-ai/sessions"));
}

QString newSessionId()
{
    return QDateTime::currentDateTime().toString(QStringLiteral("yyyyMMdd-HHmmss")) + QLatin1Char('-')
         + QString::number(QRandomGenerator::global()->bounded(0x100000u, 0xFFFFFFu), 16);
}

static QString pathFor(const QString &id)
{
    // ids are generated by newSessionId(); refuse anything that could leave the directory
    QString safe = id;
    safe.remove(QRegularExpression(QStringLiteral("[^A-Za-z0-9_-]")));
    return QDir(sessionsDir()).filePath(safe + QStringLiteral(".json"));
}

static QJsonObject metaToJson(const SessionMeta &m)
{
    return QJsonObject{{"id", m.id}, {"title", m.title}, {"kind", m.kind}, {"mode", m.mode},
                       {"dirs", QJsonArray::fromStringList(m.dirs)}, {"time", m.time.toString(Qt::ISODate)}};
}

static SessionMeta metaFromJson(const QJsonObject &o)
{
    SessionMeta m;
    m.id = o.value("id").toString(); m.title = o.value("title").toString(); m.kind = o.value("kind").toString();
    m.mode = o.value("mode").toString(); m.time = QDateTime::fromString(o.value("time").toString(), Qt::ISODate);
    for (const QJsonValue &v : o.value("dirs").toArray()) m.dirs << v.toString();
    return m;
}

bool saveSession(const SessionData &s)
{
    if (s.meta.id.isEmpty()) return false;
    QDir().mkpath(sessionsDir());
    const QJsonObject o{{"meta", metaToJson(s.meta)}, {"messages", s.messages}, {"digest", s.digest}};
    QFile f(pathFor(s.meta.id));
    if (!f.open(QIODevice::WriteOnly | QIODevice::Truncate)) return false;
    f.setPermissions(QFile::ReadOwner | QFile::WriteOwner);       // contains source code and tool output
    const bool ok = f.write(QJsonDocument(o).toJson(QJsonDocument::Compact)) > 0;
    f.close();

    // keep the 30 newest
    const QFileInfoList files = QDir(sessionsDir()).entryInfoList({QStringLiteral("*.json")}, QDir::Files, QDir::Time);
    for (int i = 30; i < files.size(); ++i) QFile::remove(files[i].absoluteFilePath());
    return ok;
}

bool loadSession(const QString &id, SessionData *out)
{
    QFile f(pathFor(id));
    if (!f.open(QIODevice::ReadOnly)) return false;
    const QJsonDocument d = QJsonDocument::fromJson(f.readAll());
    if (!d.isObject()) return false;
    const QJsonObject o = d.object();
    out->meta = metaFromJson(o.value("meta").toObject());
    out->messages = o.value("messages").toArray();
    out->digest = o.value("digest").toArray();
    return !out->meta.id.isEmpty();
}

bool deleteSession(const QString &id) { return QFile::remove(pathFor(id)); }

QList<SessionMeta> listSessions()
{
    QList<SessionMeta> out;
    const QFileInfoList files = QDir(sessionsDir()).entryInfoList({QStringLiteral("*.json")}, QDir::Files);
    for (const QFileInfo &fi : files) {
        QFile f(fi.absoluteFilePath());
        if (!f.open(QIODevice::ReadOnly)) continue;
        const QJsonObject o = QJsonDocument::fromJson(f.readAll()).object();     // reads whole file; at most 30 of them
        const SessionMeta m = metaFromJson(o.value("meta").toObject());
        if (!m.id.isEmpty()) out << m;
    }
    std::sort(out.begin(), out.end(), [](const SessionMeta &a, const SessionMeta &b) { return a.time > b.time; });
    return out;
}

QString digestForDirs(const QStringList &dirs, int maxChars)
{
    QStringList lines;
    int used = 0, found = 0;
    for (const SessionMeta &m : listSessions()) {
        bool match = false;
        for (const QString &d : m.dirs) if (dirs.contains(d)) match = true;
        if (!match) continue;
        SessionData sd;
        if (!loadSession(m.id, &sd)) continue;
        for (int i = sd.digest.size() - 1; i >= 0 && used < maxChars; --i) {
            const QJsonObject e = sd.digest[i].toObject();
            QString files;
            QStringList fl;
            for (const QJsonValue &v : e.value("files").toArray()) fl << QFileInfo(v.toString()).fileName();
            if (!fl.isEmpty()) files = QStringLiteral(" [files: %1]").arg(fl.mid(0, 8).join(QStringLiteral(", ")));
            const QString l = QStringLiteral("- %1: \"%2\" -> %3%4").arg(e.value("time").toString().left(10),
                e.value("instruction").toString().left(160), e.value("summary").toString().simplified().left(300), files);
            lines.prepend(l);
            used += l.size();
        }
        if (++found >= 3) break;
    }
    if (lines.isEmpty()) return {};
    return QStringLiteral("Earlier work in this folder (from previous sessions, oldest first):\n") + lines.join(QLatin1Char('\n'));
}

} // namespace ai
